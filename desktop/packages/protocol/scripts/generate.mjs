// Generates TypeScript from an extracted Cordial source archive.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { fromBinary } from "@bufbuild/protobuf";
import { FileDescriptorSetSchema } from "@bufbuild/protobuf/wkt";
import { fingerprint } from "./fingerprint.mjs";

const [source, destination, ...extra] = process.argv.slice(2);
if (!source || !destination || extra.length) throw new Error("Usage: generate.mjs SOURCE OUTPUT");
const root = fileURLToPath(new URL("../", import.meta.url));
const proto = resolve(source, "proto");
const config = resolve(source, "buf.yaml");
const output = resolve(destination);
const version = Number(readFileSync(join(proto, "serial/current"), "utf8").trim());
if (!Number.isInteger(version) || version <= 0 || version > 0xffffffff) throw new Error("invalid current protocol revision");
const serial = `serial/v${version}/cordial.proto`;
function files(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? files(path) : [path];
  });
}
let current;
for (const entry of readdirSync(join(proto, "serial"), { withFileTypes: true })) {
  if (!entry.isDirectory() || !/^v[1-9][0-9]*$/.test(entry.name)) continue;
  const schema = `serial/${entry.name}/cordial.proto`;
  const descriptors = fromBinary(FileDescriptorSetSchema, execFileSync("buf", [
    "build", proto, "--path", join(proto, schema), "--as-file-descriptor-set", "--config", config, "-o", "-",
  ], { cwd: root }));
  const digest = fingerprint(descriptors);
  const recorded = readFileSync(join(proto, `serial/${entry.name}/schema.sha256`), "utf8").trim();
  if (digest !== recorded) throw new Error(`Cordial serial/${entry.name} fingerprint does not match its schema`);
  if (entry.name === `v${version}`) current = digest;
}
if (!current) throw new Error("Current serial schema is missing");
execFileSync("buf", ["lint", proto, "--config", config], { cwd: root, stdio: "inherit" });
const paths = [join(proto, serial), ...files(proto).filter(path => path.endsWith(".proto") && !path.startsWith(join(proto, "serial") + "/"))];
execFileSync("buf", [
  "generate", proto, "--include-imports", ...paths.flatMap(path => ["--path", path]),
  "--config", config, "--template", join(root, "buf.gen.yaml"), "--output", output,
], { cwd: root, stdio: "inherit" });
for (const file of files(join(output, "src/gen"))) {
  writeFileSync(file, readFileSync(file, "utf8").trimEnd() + "\n");
}
function write(path, text) {
  const file = join(output, path);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
}
write("src/gen/cordial_pb.ts", `// Current operational schema. Generated by scripts/generate.mjs.\nexport * from "./serial/v${version}/cordial_pb.ts";\nexport { file_serial_v${version}_cordial as file_cordial } from "./serial/v${version}/cordial_pb.ts";\n`);
write("src/current.ts", `// Generated by scripts/generate.mjs.\nexport const CURRENT_PROTOCOL_VERSION = ${version};\n/** SHA-256 of the normalized operational descriptor set. */\nexport const OPERATIONAL_SCHEMA_SHA256 = "${current}";\n`);
